export function queueQuestion(question) {
  try {
    const queue = getOfflineQueue();
    queue.push({ question, timestamp: Date.now(), id: Date.now() });
    localStorage.setItem(QUEUE_KEY, JSON.stringify(queue));
  } catch (err) {
    console.warn('queueQuestion failed:', err);
  }
}

export function getOfflineQueue() {
  try {
    return JSON.parse(localStorage.getItem(QUEUE_KEY) || '[]');
  } catch {
    return [];
  }
}

export function removeFromQueue(id) {
  try {
    const queue = getOfflineQueue().filter(q => q.id !== id);
    localStorage.setItem(QUEUE_KEY, JSON.stringify(queue));
  } catch {
    // Storage quota fallback
  }
}

export function clearOfflineQueue() {
  localStorage.removeItem(QUEUE_KEY);
}

/**
 * Auto-sync queued questions when network returns
 */
export async function processOfflineQueue(sendFn, onSyncedCallback) {
  const queue = getOfflineQueue();
  if (queue.length === 0) return;

  console.log(`🌐 Online event detected — syncing ${queue.length} offline questions...`);
  for (const item of queue) {
    try {
      const responseText = await sendFn(item.question);
      if (responseText) {
        await saveAIAnswer(item.question, responseText);
        removeFromQueue(item.id);
        if (onSyncedCallback) onSyncedCallback(item.question, responseText);
      }
    } catch (err) {
      console.warn(`Failed to sync question "${item.question}":`, err.message);
    }
  }
}

